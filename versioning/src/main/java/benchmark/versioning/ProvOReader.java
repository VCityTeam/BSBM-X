package benchmark.versioning;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.EnumSet;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Map;
import java.util.Set;

import org.apache.jena.datatypes.xsd.XSDDateTime;
import org.apache.jena.rdf.model.Model;
import org.apache.jena.rdf.model.Property;
import org.apache.jena.rdf.model.RDFNode;
import org.apache.jena.rdf.model.ResIterator;
import org.apache.jena.rdf.model.Resource;
import org.apache.jena.rdf.model.Statement;
import org.apache.jena.rdf.model.StmtIterator;
import org.apache.jena.riot.Lang;
import org.apache.jena.riot.RDFDataMgr;
import org.apache.jena.riot.RiotException;
import org.apache.jena.sparql.core.DatasetGraph;
import org.apache.jena.sparql.core.DatasetGraphFactory;
import org.apache.jena.sparql.core.Quad;
import org.apache.jena.vocabulary.RDF;
import org.apache.jena.vocabulary.RDFS;

/**
 * Reads back a version graph from its <b>PROV-O description</b>
 * ({@code provenance.ttl}, generated by {@link ProvOWriter}), parsed with
 * Apache Jena.
 * <p>
 * The PROV-O graph is the authoritative description of the version graph:
 * <ul>
 *   <li>the versions are the {@code prov:Entity} resources in the
 *       {@link ProvOWriter#VERSION_NS} namespace;</li>
 *   <li>the DAG edges pre(v) are the {@code prov:wasDerivedFrom}
 *       statements;</li>
 *   <li>the lifecycle instants of each version are its
 *       {@code prov:generatedAtTime} and {@code prov:invalidatedAtTime}
 *       statements, when present (final versions, still valid, have no
 *       invalidation instant);</li>
 *   <li>the merge policy of every merge node is the
 *       {@code agt:policy-<POLICY>} {@code prov:SoftwareAgent} its merge
 *       activity is {@code prov:wasAssociatedWith}; the global policy of the
 *       reloaded graph is the single policy shared by all its merges, or
 *       {@code null} when they mix several per-merge policies.</li>
 * </ul>
 * The RDF dataset S(v) of each version is loaded (with Jena) from its
 * dedicated N-Quads export file ({@code <id>.nq}, written by
 * {@link VersionGraphWriter#writeEachVersionToDirectory}) located next to
 * the provenance file.
 * <p>
 * Note: {@code prov:wasDerivedFrom} statements have set semantics, so a
 * merge listing the same parent twice cannot be represented in PROV-O.
 */
public final class ProvOReader {

    /** The W3C PROV-O namespace. */
    public static final String PROV_NS = "http://www.w3.org/ns/prov#";

    /** Default name of the PROV-O file inside an export directory. */
    public static final String PROVENANCE_FILE = "provenance.ttl";

    /**
     * A version graph reconstructed from its PROV-O description: the
     * versions (with their datasets, parents, per-merge policies and
     * lifecycle instants) and the global merge policy — the single policy
     * shared by every merge, or {@code null} when the history mixes several
     * per-merge policies (each {@link Version} then carries its own).
     */
    public record ProvenanceGraph(List<Version> versions, MergePolicy policy) { }

    private ProvOReader() {
        // utility class
    }

    /**
     * Reads the version graph described by {@code <directory>/provenance.ttl},
     * loading the dataset of each version from its {@code <id>.nq} file in
     * the same directory.
     */
    public static ProvenanceGraph read(Path directory) throws IOException {
        return read(directory.resolve(PROVENANCE_FILE), directory);
    }

    /**
     * Reads the version graph described by the given PROV-O Turtle file,
     * loading the dataset of each version from its {@code <id>.nq} file in
     * {@code versionFilesDir}.
     */
    public static ProvenanceGraph read(Path provFile, Path versionFilesDir) throws IOException {
        if (!Files.isRegularFile(provFile)) {
            throw new IOException("Missing PROV-O file: " + provFile);
        }
        Model model = RDFDataMgr.loadModel(provFile.toUri().toString());
        Map<Resource, List<Resource>> parentsOf = readDerivations(model, provFile);
        Map<Resource, MergePolicy> mergePolicies = readMergePolicies(model, parentsOf, provFile);
        MergePolicy policy = globalPolicyOf(model, mergePolicies.values(), provFile);

        // Build the versions parents-first over the DAG.
        Map<Resource, Version> built = new HashMap<>();
        List<Version> versions = new ArrayList<>();
        while (built.size() < parentsOf.size()) {
            boolean progressed = false;
            List<Resource> remaining = parentsOf.keySet().stream()
                    .filter(r -> !built.containsKey(r))
                    .sorted(Comparator.comparing(Resource::getURI))
                    .toList();
            for (Resource entity : remaining) {
                List<Resource> parents = parentsOf.get(entity);
                if (!built.keySet().containsAll(parents)) {
                    continue;
                }
                String id = idOf(entity);
                Set<Quad> data = readDataset(versionFilesDir.resolve(VersionGraphWriter.fileNameOf(id)));
                Version v = new Version(id, data, parents.stream().map(built::get).toList(),
                        mergePolicies.get(entity),
                        readInstant(entity, "generatedAtTime", provFile),
                        readInstant(entity, "invalidatedAtTime", provFile));
                built.put(entity, v);
                versions.add(v);
                progressed = true;
            }
            if (!progressed) {
                throw new IOException("Cycle detected in the prov:wasDerivedFrom graph of " + provFile);
            }
        }
        return new ProvenanceGraph(versions, policy);
    }

    /**
     * The policy of each merge entity (two parents or more): the
     * {@code agt:policy-<POLICY>} agent its generating activity is
     * {@code prov:wasAssociatedWith} ({@link ProvOWriter}'s convention). A
     * merge whose activity carries no association falls back to the single
     * policy agent declared in the file (as written before the policies were
     * recorded per merge); with several agents declared the association is
     * required, otherwise the merge would be ambiguous.
     */
    private static Map<Resource, MergePolicy> readMergePolicies(Model model,
            Map<Resource, List<Resource>> parentsOf, Path provFile) throws IOException {
        List<MergePolicy> declared = declaredPolicies(model, provFile);
        Property wasGeneratedBy = model.createProperty(PROV_NS, "wasGeneratedBy");
        Property wasAssociatedWith = model.createProperty(PROV_NS, "wasAssociatedWith");

        Map<Resource, MergePolicy> policies = new HashMap<>();
        for (Map.Entry<Resource, List<Resource>> entry : parentsOf.entrySet()) {
            if (entry.getValue().size() < 2) {
                continue;
            }
            Resource entity = entry.getKey();
            MergePolicy policy = associatedPolicy(entity, wasGeneratedBy, wasAssociatedWith, provFile);
            if (policy == null && declared.size() == 1) {
                policy = declared.get(0);
            }
            if (policy == null) {
                throw new IOException("No merge-policy agent associated with the merge "
                        + entity.getURI() + " in " + provFile);
            }
            policies.put(entity, policy);
        }
        return policies;
    }

    /**
     * The policy agent associated with the activity that generated the given
     * entity, or {@code null} when there is none.
     */
    private static MergePolicy associatedPolicy(Resource entity, Property wasGeneratedBy,
            Property wasAssociatedWith, Path provFile) throws IOException {
        StmtIterator activities = entity.listProperties(wasGeneratedBy);
        while (activities.hasNext()) {
            RDFNode activity = activities.next().getObject();
            if (!activity.isResource()) {
                continue;
            }
            StmtIterator agents = activity.asResource().listProperties(wasAssociatedWith);
            while (agents.hasNext()) {
                MergePolicy policy = policyOf(agents.next().getObject(), provFile);
                if (policy != null) {
                    return policy;
                }
            }
        }
        return null;
    }

    /**
     * All the {@code agt:policy-<POLICY>} software agents declared in the
     * file, without duplicates.
     */
    private static List<MergePolicy> declaredPolicies(Model model, Path provFile) throws IOException {
        Resource agentType = model.createResource(PROV_NS + "SoftwareAgent");
        List<MergePolicy> declared = new ArrayList<>();
        ResIterator it = model.listSubjectsWithProperty(RDF.type, agentType);
        while (it.hasNext()) {
            MergePolicy policy = policyOf(it.next(), provFile);
            if (policy != null && !declared.contains(policy)) {
                declared.add(policy);
            }
        }
        return declared;
    }

    /**
     * The policy named by an {@code agt:policy-<POLICY>} node, {@code null}
     * for any other node.
     */
    private static MergePolicy policyOf(RDFNode agent, Path provFile) throws IOException {
        String prefix = ProvOWriter.AGENT_NS + "policy-";
        if (!agent.isURIResource() || !agent.asResource().getURI().startsWith(prefix)) {
            return null;
        }
        String name = agent.asResource().getURI().substring(prefix.length());
        try {
            return MergePolicy.valueOf(name);
        } catch (IllegalArgumentException e) {
            throw new IOException("Unknown merge policy '" + name + "' in " + provFile, e);
        }
    }

    /**
     * The global policy of the history: the single policy shared by all its
     * merges — for a merge-free history, the single declared policy agent —
     * or {@code null} when the merges mix several per-merge policies (or
     * nothing is declared at all).
     */
    private static MergePolicy globalPolicyOf(Model model, Collection<MergePolicy> mergePolicies,
            Path provFile) throws IOException {
        Set<MergePolicy> distinct = EnumSet.noneOf(MergePolicy.class);
        distinct.addAll(mergePolicies);
        if (distinct.size() == 1) {
            return distinct.iterator().next();
        }
        if (distinct.isEmpty()) {
            List<MergePolicy> declared = declaredPolicies(model, provFile);
            if (declared.size() == 1) {
                return declared.get(0);
            }
        }
        return null;
    }

    /**
     * Collects the version entities and their parents from the
     * {@code prov:wasDerivedFrom} statements.
     */
    private static Map<Resource, List<Resource>> readDerivations(Model model, Path provFile) throws IOException {
        Resource entityType = model.createResource(PROV_NS + "Entity");
        Property wasDerivedFrom = model.createProperty(PROV_NS, "wasDerivedFrom");

        Map<Resource, List<Resource>> parentsOf = new HashMap<>();
        ResIterator it = model.listSubjectsWithProperty(RDF.type, entityType);
        while (it.hasNext()) {
            Resource entity = it.next();
            if (!entity.isURIResource() || !entity.getURI().startsWith(ProvOWriter.VERSION_NS)) {
                continue;
            }
            List<Resource> parents = new ArrayList<>();
            StmtIterator st = entity.listProperties(wasDerivedFrom);
            while (st.hasNext()) {
                parents.add(st.next().getObject().asResource());
            }
            // RDF statements are unordered; sort for determinism (the merge
            // operators are commutative, so parent order is irrelevant).
            parents.sort(Comparator.comparing(Resource::getURI));
            parentsOf.put(entity, parents);
        }
        if (parentsOf.isEmpty()) {
            throw new IOException("No version entity found in " + provFile);
        }
        for (Map.Entry<Resource, List<Resource>> e : parentsOf.entrySet()) {
            for (Resource parent : e.getValue()) {
                if (!parentsOf.containsKey(parent)) {
                    throw new IOException("Version " + e.getKey().getURI() + " is derived from "
                            + parent.getURI() + ", which is not described in " + provFile);
                }
            }
        }
        return parentsOf;
    }

    /**
     * The {@code prov:generatedAtTime}/{@code prov:invalidatedAtTime}
     * instant of a version entity, or {@code null} when absent (final
     * versions have no invalidation instant, and older provenance files
     * carry no timestamps at all).
     */
    private static Instant readInstant(Resource entity, String provProperty, Path provFile) throws IOException {
        Statement statement = entity.getProperty(
                entity.getModel().createProperty(PROV_NS, provProperty));
        if (statement == null) {
            return null;
        }
        try {
            Object value = statement.getLiteral().getValue();
            if (value instanceof XSDDateTime dateTime) {
                return dateTime.asCalendar().toInstant();
            }
            return Instant.parse(statement.getLiteral().getLexicalForm());
        } catch (RuntimeException e) {
            throw new IOException("Invalid prov:" + provProperty + " on " + entity.getURI()
                    + " in " + provFile, e);
        }
    }

    /**
     * The version id, recovered from the {@code rdfs:label} ("Version &lt;id&gt;")
     * when present, otherwise from the IRI local name (which
     * {@link ProvOWriter} sanitizes).
     */
    private static String idOf(Resource entity) {
        Statement label = entity.getProperty(RDFS.label);
        if (label != null && label.getObject().isLiteral()) {
            String text = label.getString();
            if (text.startsWith("Version ")) {
                return text.substring("Version ".length());
            }
        }
        return entity.getURI().substring(ProvOWriter.VERSION_NS.length());
    }

    /**
     * Parses a version dataset file written by
     * {@link VersionGraphWriter#writeEachVersionToDirectory} as N-Quads,
     * using Apache Jena. The {@code #} comment header is skipped by the
     * N-Quads parser.
     */
    private static Set<Quad> readDataset(Path file) throws IOException {
        if (!Files.isRegularFile(file)) {
            throw new IOException("Missing version dataset file: " + file);
        }
        DatasetGraph dsg = DatasetGraphFactory.createGeneral();
        try {
            RDFDataMgr.read(dsg, file.toUri().toString(), Lang.NQUADS);
        } catch (RiotException e) {
            throw new IOException("Invalid N-Quads in version dataset file " + file, e);
        }
        Set<Quad> quads = new HashSet<>();
        Iterator<Quad> it = dsg.find();
        while (it.hasNext()) {
            quads.add(it.next());
        }
        return quads;
    }
}
