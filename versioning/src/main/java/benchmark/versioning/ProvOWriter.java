package benchmark.versioning;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.Collection;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

import org.apache.jena.datatypes.xsd.XSDDatatype;
import org.apache.jena.rdf.model.Literal;
import org.apache.jena.rdf.model.Model;
import org.apache.jena.rdf.model.ModelFactory;
import org.apache.jena.rdf.model.Property;
import org.apache.jena.rdf.model.Resource;
import org.apache.jena.riot.Lang;
import org.apache.jena.riot.RDFDataMgr;
import org.apache.jena.vocabulary.RDF;
import org.apache.jena.vocabulary.RDFS;
import org.apache.jena.vocabulary.XSD;

/**
 * Serializes a version graph as an RDF graph using the W3C PROV-O ontology
 * (<a href="https://www.w3.org/TR/prov-o/">https://www.w3.org/TR/prov-o/</a>),
 * built and written in Turtle with Apache Jena.
 * <p>
 * Mapping of the formal model onto PROV-O:
 * <ul>
 *   <li>Every version {@code v ∈ V} is a {@code prov:Entity}, carrying its
 *       {@code prov:generatedAtTime} (when it was generated) and, unless it
 *       is a final version (still valid), its {@code prov:invalidatedAtTime}
 *       — the instant its following versions were generated (see
 *       {@link VersionTimestamps});</li>
 *   <li>Every edge {@code (u, v) ∈ A} becomes {@code v prov:wasDerivedFrom u};</li>
 *   <li>Every transition node (|pre(v)| = 1) is generated by a
 *       {@code prov:Activity} of type "transition" that {@code prov:used}
 *       the parent version;</li>
 *   <li>Every merge node (|pre(v)| ≥ 2) is generated by a
 *       {@code prov:Activity} of type "merge" that {@code prov:used} all
 *       the parent versions and is {@code prov:wasAssociatedWith} the
 *       policy of <b>that merge</b> ({@link Version#getMergePolicy()}, the
 *       global policy for versions that carry none), modelled as a
 *       {@code prov:SoftwareAgent} — one agent per policy used, so
 *       histories mixing per-merge policies round-trip faithfully;</li>
 *   <li>Root nodes (|pre(v)| = 0) are plain entities with no generation
 *       activity.</li>
 * </ul>
 * The IRIs minted for versions and activities live in their own namespaces,
 * distinct from the named graphs used inside the RDF datasets S(v).
 */
public final class ProvOWriter {

    /** Namespace of the version entities. */
    public static final String VERSION_NS = "http://example.org/versioning/version/";
    /** Namespace of the transition/merge activities. */
    public static final String ACTIVITY_NS = "http://example.org/versioning/activity/";
    /** Namespace of the agents (the global merge policy). */
    public static final String AGENT_NS = "http://example.org/versioning/agent/";
    /** The W3C PROV-O namespace. */
    private static final String PROV_NS = "http://www.w3.org/ns/prov#";

    private ProvOWriter() {
        // utility class
    }

    /**
     * Writes the PROV-O description of the graph into the given Turtle file,
     * overwriting it if it already exists.
     */
    public static void writeToFile(VersionGraph graph, Path file) throws IOException {
        writeToFile(graph.getVersions(), graph.getGlobalPolicy(), file);
    }

    /**
     * Writes the PROV-O description of the given versions into the given
     * Turtle file, overwriting it if it already exists. The policy is the
     * global one, applied to merges that carry no policy of their own; it
     * may be {@code null} when every merge does.
     */
    public static void writeToFile(Collection<Version> versions, MergePolicy policy, Path file) throws IOException {
        if (file.getParent() != null) {
            Files.createDirectories(file.getParent());
        }
        Files.writeString(file, serialize(versions, policy), StandardCharsets.UTF_8);
    }

    /**
     * Serializes the PROV-O description of the given versions to Turtle,
     * using Apache Jena.
     */
    public static String serialize(Collection<Version> versions, MergePolicy policy) {
        Model model = buildModel(versions, policy);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        RDFDataMgr.write(out, model, Lang.TURTLE);
        return out.toString(StandardCharsets.UTF_8);
    }

    /**
     * Builds the PROV-O description of the given versions as a Jena model —
     * the same model that {@link #serialize} writes as Turtle. Used by
     * {@link InferenceValidator#inferMetagraph} to reason over the metagraph.
     */
    public static Model model(Collection<Version> versions, MergePolicy policy) {
        return buildModel(versions, policy);
    }

    /**
     * Builds the Jena model describing the version graph in PROV-O.
     */
    private static Model buildModel(Collection<Version> versions, MergePolicy policy) {
        List<Version> ordered = VersionGraphWriter.topologicalOrder(versions);

        Model model = ModelFactory.createDefaultModel();
        model.setNsPrefix("prov", PROV_NS);
        model.setNsPrefix("rdfs", RDFS.getURI());
        model.setNsPrefix("xsd", XSD.getURI());
        model.setNsPrefix("ver", VERSION_NS);
        model.setNsPrefix("act", ACTIVITY_NS);
        model.setNsPrefix("agt", AGENT_NS);

        Resource entityType = model.createResource(PROV_NS + "Entity");
        Resource activityType = model.createResource(PROV_NS + "Activity");
        Resource softwareAgentType = model.createResource(PROV_NS + "SoftwareAgent");
        Property wasDerivedFrom = model.createProperty(PROV_NS + "wasDerivedFrom");
        Property wasGeneratedBy = model.createProperty(PROV_NS + "wasGeneratedBy");
        Property used = model.createProperty(PROV_NS + "used");
        Property generated = model.createProperty(PROV_NS + "generated");
        Property wasAssociatedWith = model.createProperty(PROV_NS + "wasAssociatedWith");
        Property generatedAtTime = model.createProperty(PROV_NS + "generatedAtTime");
        Property invalidatedAtTime = model.createProperty(PROV_NS + "invalidatedAtTime");

        // One prov:SoftwareAgent per merge policy used. The global policy is
        // declared even when no merge uses it, so a merge-free history still
        // records how it was generated; null (per-merge policies only)
        // declares nothing up front.
        Map<MergePolicy, Resource> agents = new EnumMap<>(MergePolicy.class);
        if (policy != null) {
            agentOf(model, agents, policy, softwareAgentType);
        }

        for (Version v : ordered) {
            Resource entity = model.createResource(entityIri(v))
                    .addProperty(RDF.type, entityType)
                    .addProperty(RDFS.label, "Version " + v.getId())
                    .addProperty(RDFS.comment, kindOf(v) + " node with " + v.getData().size() + " quad(s)");
            if (v.getGeneratedAtTime() != null) {
                entity.addProperty(generatedAtTime, dateTime(model, v.getGeneratedAtTime()));
            }
            // Final versions are still valid: no prov:invalidatedAtTime.
            if (v.getInvalidatedAtTime() != null) {
                entity.addProperty(invalidatedAtTime, dateTime(model, v.getInvalidatedAtTime()));
            }

            List<Version> parents = v.getParents();
            if (parents.isEmpty()) {
                continue;
            }

            boolean merge = parents.size() >= 2;
            MergePolicy mergePolicy = null;
            if (merge) {
                mergePolicy = v.getMergePolicy() != null ? v.getMergePolicy() : policy;
                if (mergePolicy == null) {
                    throw new IllegalArgumentException("Merge " + v.getId()
                            + " carries no merge policy and no global policy was given");
                }
            }
            Resource activity = model.createResource(activityIri(v))
                    .addProperty(RDF.type, activityType)
                    .addProperty(RDFS.label,
                            (merge ? "Merge (" + parents.size() + " parents, policy " + mergePolicy.name() + ")"
                                    : "Transition") + " producing " + v.getId());

            for (Version parent : parents) {
                Resource parentEntity = model.createResource(entityIri(parent));
                entity.addProperty(wasDerivedFrom, parentEntity);
                activity.addProperty(used, parentEntity);
            }
            entity.addProperty(wasGeneratedBy, activity);
            activity.addProperty(generated, entity);
            if (merge) {
                activity.addProperty(wasAssociatedWith,
                        agentOf(model, agents, mergePolicy, softwareAgentType));
            }
        }
        return model;
    }

    /**
     * The {@code prov:SoftwareAgent} of a merge policy
     * ({@code agt:policy-<POLICY>}), declared on first use.
     */
    private static Resource agentOf(Model model, Map<MergePolicy, Resource> agents,
                                    MergePolicy policy, Resource softwareAgentType) {
        return agents.computeIfAbsent(policy, p -> model.createResource(AGENT_NS + "policy-" + p.name())
                .addProperty(RDF.type, softwareAgentType)
                .addProperty(RDFS.label, "Merge policy " + p.name()));
    }

    private static Literal dateTime(Model model, Instant instant) {
        return model.createTypedLiteral(instant.toString(), XSDDatatype.XSDdateTime);
    }

    /**
     * The IRI of the {@code prov:Entity} describing the version with the
     * given id (the id is sanitized the same way {@link #serialize} mints
     * the entity IRIs).
     */
    public static String entityIriOf(String versionId) {
        return VERSION_NS + localName(versionId);
    }

    private static String entityIri(Version v) {
        return entityIriOf(v.getId());
    }

    private static String activityIri(Version v) {
        String kind = v.getParents().size() >= 2 ? "merge-" : "transition-";
        return ACTIVITY_NS + kind + localName(v.getId());
    }

    private static String localName(String id) {
        return id.replaceAll("[^A-Za-z0-9._-]", "_");
    }

    private static String kindOf(Version v) {
        int parents = v.getParents().size();
        if (parents == 0) {
            return "root";
        }
        if (parents == 1) {
            return "transition";
        }
        return "merge";
    }
}
